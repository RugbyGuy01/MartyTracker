// Configuration cache freezes anything computed in the android {} block above, so the
// build date is instead generated by a task that always re-runs at execution time and is
// wired in as a generated source directory via the Variant API.
abstract class GenerateBuildDateTask : DefaultTask() {
    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val buildDate = DateTimeFormatter.ofPattern("MMM d, yyyy h:mm a").format(ZonedDateTime.now())
        val packageDir = outputDir.get().asFile.resolve("com/golfpvcc/martytracker")
        packageDir.mkdirs()
        packageDir.resolve("BuildInfo.kt").writeText(
            """
            package com.golfpvcc.martytracker

            object BuildInfo {
                const val BUILD_DATE = "$buildDate"
            }
            """.trimIndent()
        )
    }
}

androidComponents {
    onVariants { variant ->
        val taskProvider = tasks.register(
            "generate${variant.name.replaceFirstChar { it.uppercase() }}BuildDate",
            GenerateBuildDateTask::class.java
        ) {
            outputs.upToDateWhen { false }
        }
        variant.sources.java?.addGeneratedSourceDirectory(taskProvider, GenerateBuildDateTask::outputDir)
    }
}

